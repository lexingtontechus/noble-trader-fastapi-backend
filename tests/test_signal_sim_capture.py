"""
Tests for the nt_signal_sim capture path + EOD correction helpers.

Covers:
  - NT_SIGNAL_SIM_COLUMNS filtering (drops unknown keys, keeps known ones)
  - _build_signal_sim_payload produces the expected row shape
  - bayesian_adjusted_p_win formula (self-correction)
  - _classify_bias thresholds (OVERCONFIDENT / UNDERCONFIDENT / CALIBRATED)
"""

import pytest

from regime_platform.sweep_orchestrator.supabase_client import (
    NT_SIGNAL_SIM_COLUMNS,
    _filter_payload,
)
from regime_platform.sweep_orchestrator.orchestrator import _build_signal_sim_payload
from regime_platform.sweep_orchestrator.eod_correction import (
    bayesian_adjusted_p_win,
    _classify_bias,
)


class TestSignalSimColumns:
    def test_columns_include_capture_fields(self):
        for col in (
            "signal_id", "symbol", "venue", "ts", "signal",
            "entry_price", "stop_loss", "take_profit",
            "brick_size", "sl_bricks", "tp_bricks",
            "p_win", "ev", "regime", "regime_conf", "source", "qualified",
        ):
            assert col in NT_SIGNAL_SIM_COLUMNS, f"missing capture column: {col}"

    def test_columns_include_resolver_fields(self):
        for col in (
            "outcome", "exit_price", "exit_ts", "hold_bars",
            "mfe", "mae", "pnl_bricks", "pnl_dollars", "resolved_at",
        ):
            assert col in NT_SIGNAL_SIM_COLUMNS, f"missing resolver column: {col}"

    def test_filter_payload_drops_unknown_keeps_known(self):
        payload = {
            "symbol": "AUDUSD", "venue": "OANDA", "ts": "2026-08-06T00:00:00Z",
            "signal": "buy", "entry_price": 0.69, "stop_loss": 0.688,
            "take_profit": 0.694, "brick_size": 0.001, "sl_bricks": 3,
            "tp_bricks": 6, "p_win": 0.55, "ev": 1.2, "regime": "bull",
            "regime_conf": 0.8, "source": "sweep-light", "qualified": True,
            "not_a_column": "should_be_dropped",
        }
        clean = _filter_payload(payload, NT_SIGNAL_SIM_COLUMNS)
        assert "not_a_column" not in clean
        assert clean["symbol"] == "AUDUSD"
        assert clean["qualified"] is True

    def test_filter_payload_drops_none_outcome_columns(self):
        # Resolver-only fields should not appear at capture time
        payload = {"symbol": "EURUSD", "outcome": "tp_hit", "pnl_dollars": 1.0}
        clean = _filter_payload(payload, NT_SIGNAL_SIM_COLUMNS)
        # They ARE in the frozenset, so they survive filtering — but capture
        # payload construction never sets them (they stay null in Supabase).
        assert "outcome" in clean


class TestBuildSignalSimPayload:
    def test_payload_shape(self):
        payload = _build_signal_sim_payload(
            symbol="XAUUSD",
            venue="OANDA",
            ts="2026-08-06T00:00:00Z",
            signal="buy",
            entry_price=4030.325,
            stop_loss=4027.325,
            take_profit=4033.325,
            brick_size=1.0,
            sl_bricks=3,
            tp_bricks=6,
            p_win=0.58,
            ev=1.5,
            regime="high_vol_bull",
            regime_conf=0.9,
            source="sweep-heavy",
            qualified=True,
            kelly_f=0.08,
            effective_kelly=0.12,
        )
        assert payload["symbol"] == "XAUUSD"
        assert payload["signal"] == "buy"
        assert payload["entry_price"] == 4030.325
        assert payload["source"] == "sweep-heavy"
        assert payload["qualified"] is True
        assert payload["sl_bricks"] == 3
        assert payload["tp_bricks"] == 6
        # Part II: kelly sizing inputs flow through for the paper book
        assert payload["kelly_f"] == pytest.approx(0.08)
        assert payload["effective_kelly"] == pytest.approx(0.12)

    def test_payload_has_no_signal_id(self):
        # signal_id is generated by log_signal_sim (not the payload builder)
        payload = _build_signal_sim_payload(
            symbol="EURUSD", venue="OANDA", ts="2026-08-06T00:00:00Z",
            signal="sell", entry_price=1.10, stop_loss=1.11, take_profit=1.09,
            brick_size=0.001, sl_bricks=3, tp_bricks=6, p_win=0.5, ev=0.0,
            regime="unknown", regime_conf=0.5, source="sweep-light", qualified=False,
        )
        assert "signal_id" not in payload

    def test_log_signal_sim_adds_signal_id(self, monkeypatch):
        # log_signal_sim must inject a UUID before insert (PK has no default)
        import uuid as _uuid
        from regime_platform.sweep_orchestrator.supabase_client import log_signal_sim

        captured = {}

        async def fake_insert(table, payload, **_kw):
            captured["table"] = table
            captured["payload"] = dict(payload)
            return True

        monkeypatch.setattr("regime_platform.sweep_orchestrator.supabase_client._insert_row", fake_insert)
        monkeypatch.setattr("regime_platform.core.settings.settings.SUPABASE_URL", "https://example.supabase.co")

        payload = _build_signal_sim_payload(
            symbol="AUDUSD", venue="OANDA", ts="2026-08-06T00:00:00Z",
            signal="buy", entry_price=0.69, stop_loss=0.688, take_profit=0.694,
            brick_size=0.001, sl_bricks=3, tp_bricks=6, p_win=0.55, ev=1.2,
            regime="bull", regime_conf=0.8, source="sweep-light", qualified=True,
        )

        import asyncio
        asyncio.run(log_signal_sim(payload))

        assert captured["table"] == "nt_signal_sim"
        assert "signal_id" in captured["payload"]
        # valid UUID v4
        _uuid.UUID(captured["payload"]["signal_id"])


class TestBayesianAdjustment:
    def test_few_records_prior_dominates(self):
        # p_win 0.9 with only 2 records → pulled toward 0.5
        adj = bayesian_adjusted_p_win(0.9, n_records=2)
        assert adj < 0.9
        assert adj > 0.5

    def test_many_records_observed_dominates(self):
        # p_win 0.7 with 1000 records → stays near 0.7
        adj = bayesian_adjusted_p_win(0.7, n_records=1000)
        assert adj == pytest.approx(0.699, abs=0.01)

    def test_formula_exact(self):
        # (0.6*10 + 0.5*10) / 20 = 0.55
        adj = bayesian_adjusted_p_win(0.6, n_records=10)
        assert adj == pytest.approx(0.55, abs=0.0001)

    def test_none_safe(self):
        assert bayesian_adjusted_p_win(None, 0) == pytest.approx(0.5, abs=0.0001)


class TestClassifyBias:
    def test_overconfident(self):
        assert _classify_bias(0.15) == "OVERCONFIDENT"

    def test_underconfident(self):
        assert _classify_bias(-0.15) == "UNDERCONFIDENT"

    def test_calibrated_boundaries(self):
        assert _classify_bias(0.10) == "CALIBRATED"
        assert _classify_bias(-0.10) == "CALIBRATED"
        assert _classify_bias(0.0) == "CALIBRATED"
