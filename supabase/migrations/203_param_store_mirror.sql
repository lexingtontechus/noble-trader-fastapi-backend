-- 203_param_store_mirror.sql
--
-- 2026-10-08 — single source of truth for runtime-mutated parameters.
-- Worklog: worklog/20261008_PARAM_SOURCE_OF_TRUTH.md
--
-- CONTEXT
-- -------
-- The pre-sweep dynamic tier optimizer (dynamic_tier_optimizer.py) wrote
-- its freshly-computed parameters to `nt_dynamic_tier_state` — a network
-- round-trip to a DB the sweep then had to read back, and (as measured
-- 2026-10-08) never actually did. Parameters are LOCAL runtime state: the
-- process that computes them and the process that consumes them run in
-- the SAME Studio process on the SAME persistent volume.
--
-- The single source of truth is now `config/param_store.sqlite`
-- (regime_platform/core/param_store.py), gitignored, written by the
-- optimizer, read by the sweep on the hot path. This table is the
-- DURABLE AUDIT MIRROR + cross-instance fallback — never the read path
-- for an optimization.
--
-- NOTE ON NUMBERING: this table already existed in production, created
-- out-of-band (it has no prior migration file). This migration makes the
-- repo reproducible. It reflects the EXISTING production shape exactly
-- (verified against information_schema.columns / pg_constraint /
-- pg_policies on 2026-10-08) so applying it against production is a
-- genuine no-op — every statement is guarded and no duplicate index or
-- policy is created.
--
-- `tier_value` is TEXT. Numeric tiers (dynamic_atr) store a float repr;
-- structured tiers (regime_edge carries {win_rate, expectancy_r},
-- dynamic_deadline carries {soft,hard,median,confidence}, brick_state
-- carries the nt_brick_params_state payload) store a JSON string.
-- Consumers that need the object use param_store.read_dict() locally.

CREATE TABLE IF NOT EXISTS nt_dynamic_tier_state (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol      TEXT        NOT NULL,
    tier_type   TEXT        NOT NULL,
    tier_key    TEXT        NOT NULL,
    tier_value  TEXT        NOT NULL,
    n           INTEGER     NOT NULL DEFAULT 0,
    computed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    source      TEXT        NOT NULL DEFAULT 'dynamic_tier_optimizer',
    CONSTRAINT nt_dynamic_tier_state_symbol_tier_type_tier_key_key
        UNIQUE (symbol, tier_type, tier_key)
);

CREATE INDEX IF NOT EXISTS idx_dynamic_tier_state_symbol
    ON nt_dynamic_tier_state (symbol, tier_type);

CREATE INDEX IF NOT EXISTS idx_dynamic_tier_state_computed
    ON nt_dynamic_tier_state (computed_at DESC);

-- RLS + service-role policy (production policy name preserved so the
-- guarded CREATE does not add a second policy).
ALTER TABLE nt_dynamic_tier_state ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE tablename = 'nt_dynamic_tier_state'
          AND policyname = 'Service role full access'
    ) THEN
        CREATE POLICY "Service role full access"
            ON nt_dynamic_tier_state
            FOR ALL
            TO service_role
            USING (true)
            WITH CHECK (true);
    END IF;
END $$;

-- PostgREST must see the table immediately (stale schema cache → PGRST204).
NOTIFY pgrst, 'reload schema';
